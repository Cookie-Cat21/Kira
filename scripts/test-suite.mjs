const notEmpty = { fn: "notEmpty" };
const noSi = { fn: "noUnicode", args: ["si"] };
const noTa = { fn: "noUnicode", args: ["ta"] };
const hasSi = { fn: "hasUnicode", args: ["si"] };
const hasTa = { fn: "hasUnicode", args: ["ta"] };
const eventHasProducts = { fn: "eventHasProducts" };
const noHallucinatedProducts = { fn: "noHallucinatedProducts" };
const badRequest = { fn: "httpStatus", args: [400] };

function req({ messages, language = "en", cart = [], ...rest }) {
  return { messages, cart, language, ...rest };
}

function test({
  id,
  name,
  group,
  subgroup,
  messages,
  language = "en",
  cart = [],
  request = {},
  endpoint,
  method,
  checks,
  notes = "",
  autoFixable = false,
}) {
  return {
    id,
    name,
    group,
    subgroup,
    request: req({ messages, language, cart, ...request }),
    ...(endpoint ? { endpoint } : {}),
    ...(method ? { method } : {}),
    checks,
    notes,
    autoFixable,
  };
}

